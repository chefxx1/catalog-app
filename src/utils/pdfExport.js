import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

const BRAND_START = [37, 99, 235];
const BRAND_MID = [124, 58, 237];
const BRAND_END = [16, 185, 129];
const TEXT_DARK = [24, 24, 27];
const TEXT_MUTED = [113, 113, 122];

const loadImage = (url) =>
  new Promise((resolve) => {
    if (!url) return resolve(null);
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => {
      try {
        const canvas = document.createElement("canvas");
        const max = 400;
        let w = img.width, h = img.height;
        if (w > max || h > max) {
          if (w > h) { h = Math.round(h * max / w); w = max; }
          else { w = Math.round(w * max / h); h = max; }
        }
        canvas.width = w; canvas.height = h;
        canvas.getContext("2d").drawImage(img, 0, 0, w, h);
        resolve({ data: canvas.toDataURL("image/jpeg", 0.85), w, h });
      } catch {
        resolve(null);
      }
    };
    img.onerror = () => resolve(null);
    img.src = url;
  });

const drawHeader = (doc, storeName) => {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...BRAND_START);
  doc.rect(0, 0, w / 3, 4, "F");
  doc.setFillColor(...BRAND_MID);
  doc.rect(w / 3, 0, w / 3, 4, "F");
  doc.setFillColor(...BRAND_END);
  doc.rect((w * 2) / 3, 0, w / 3, 4, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(...TEXT_DARK);
  doc.text("Catalog", 14, 20);
  doc.setTextColor(...BRAND_MID);
  doc.text("AI", 14 + doc.getTextWidth("Catalog") + 2, 20);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...TEXT_MUTED);
  doc.text(storeName || "Product Catalog", w - 14, 20, { align: "right" });
  doc.setFontSize(8);
  doc.text(new Date().toLocaleDateString(), w - 14, 26, { align: "right" });

  doc.setDrawColor(230, 230, 230);
  doc.line(14, 32, w - 14, 32);
};

const drawFooter = (doc, pageNum, totalPages) => {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setFontSize(8);
  doc.setTextColor(...TEXT_MUTED);
  doc.text("Generated by CatalogAI", 14, h - 8);
  doc.text(`Page ${pageNum} of ${totalPages}`, w - 14, h - 8, { align: "right" });
};

export const generateProductPdf = async (product, storeName) => {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  drawHeader(doc, storeName);

  let y = 42;
  const img = await loadImage(product.image_url || product.thumbnail);
  if (img) {
    const maxW = 70, maxH = 70;
    let iw = img.w, ih = img.h;
    const ratio = Math.min(maxW / iw, maxH / ih);
    iw *= ratio; ih *= ratio;
    doc.addImage(img.data, "JPEG", 14, y, iw, ih);
  }

  const textX = img ? 90 : 14;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(...TEXT_DARK);
  const nameLines = doc.splitTextToSize(product.name || "Untitled", 110);
  doc.text(nameLines, textX, y + 8);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...TEXT_MUTED);
  if (product.brand) doc.text(product.brand, textX, y + 8 + nameLines.length * 6 + 2);

  if (product.price) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(16);
    doc.setTextColor(...BRAND_END);
    doc.text(`$${product.price}`, textX, y + 8 + nameLines.length * 6 + 14);
  }

  y = Math.max(y + 80, y + 8 + nameLines.length * 6 + 22);

  if (product.description || product.ai_description_professional || product.edited_description) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(...TEXT_DARK);
    doc.text("Description", 14, y);
    y += 5;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(...TEXT_MUTED);
    const descText = product.ai_description_professional || product.edited_description || product.description;
    const descLines = doc.splitTextToSize(String(descText), 180);
    doc.text(descLines, 14, y);
    y += descLines.length * 5 + 6;
  }

  const details = [
    ["Barcode", product.barcode],
    ["Category", product.category || product.ai_category_suggestion],
    ["Status", product.status],
    ["Stock", product.stock_quantity != null ? String(product.stock_quantity) : null],
  ].filter((r) => r[1]);

  if (details.length) {
    autoTable(doc, {
      startY: y,
      head: [["Attribute", "Value"]],
      body: details,
      theme: "grid",
      headStyles: { fillColor: BRAND_MID, textColor: 255, fontStyle: "bold" },
      styles: { fontSize: 9, cellPadding: 3 },
      margin: { left: 14, right: 14 },
    });
    y = doc.lastAutoTable.finalY + 6;
  }

  const total = doc.internal.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    drawFooter(doc, i, total);
  }

  return doc.output("blob");
};

export const generateCatalogPdf = async (entries, storeName) => {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const w = doc.internal.pageSize.getWidth();
  drawHeader(doc, storeName);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(...TEXT_DARK);
  doc.text("Product Catalog", 14, 42);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...TEXT_MUTED);
  doc.text(`${entries.length} product${entries.length !== 1 ? "s" : ""}`, 14, 48);

  const rows = entries.map((e) => [
    e.custom_name || e.name || "",
    e.barcode || "-",
    e.ai_category_suggestion || e.category || "-",
    e.custom_price ? `$${e.custom_price}` : (e.price ? `$${e.price}` : "-"),
    e.stock_quantity != null ? String(e.stock_quantity) : "-",
    e.status || "-",
  ]);

  const head = [["Product", "Barcode", "Category", "Price", "Stock", "Status"]];

  autoTable(doc, {
    startY: 54,
    head,
    body: rows,
    theme: "striped",
    headStyles: { fillColor: BRAND_MID, textColor: 255, fontStyle: "bold", fontSize: 10 },
    styles: { fontSize: 9, cellPadding: 3 },
    alternateRowStyles: { fillColor: [248, 248, 250] },
    margin: { left: 14, right: 14 },
    didDrawPage: () => { drawHeader(doc, storeName); },
  });

  const total = doc.internal.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    drawFooter(doc, i, total);
  }

  return doc.output("blob");
};
